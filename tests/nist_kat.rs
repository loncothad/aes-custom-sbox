//! Known-answer tests from NIST publications, run through the public API.
//!
//! Sources:
//! - FIPS-197 upd1, Appendices C.1-C.3
//! - NIST SP 800-38A, Sections F.1.1, F.2.1 and F.3.1 (ECB)
